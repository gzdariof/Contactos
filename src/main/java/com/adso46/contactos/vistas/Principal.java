    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        Contacto elContacto = new Contacto();
        elContacto.setNombreCompleto(txtNombreCompleto.getText());
        elContacto.setCorreoElectronico(txtCorreoElectronico.getText());
        elContacto.setGenero(cbxGenero.getSelectedIndex());
        elContacto.setEsCasado(chkEsCasado.isSelected()? true : false);
        elContacto.setTieneCasaPropia(rdbSi.isSelected()? true : false);
        //txareaSalida.append(elContacto.toString());
        ContactosController.AgregarContacto(elContacto);
        txareaSalida.setText(elContacto.toString());
    }//GEN-LAST:event_btnAgregarActionPerformed

